#!/usr/bin/env python3
"""Loads the VoiceShop synthetic catalog (VoiceShop-CatalogCuration CodeBuild job).

The catalog ships in this package as catalog/<name>.zip (catalog.jsonl, images/,
manifest.json), generated by generate/generate_catalog.py and pinned by
catalog/catalog.lock.json. This job checks the zip against the lock, uploads each
product image to the private images bucket, embeds each product with Titan Text
Embeddings V2, writes the Products table and CATALOG#META, and removes products
and images that are no longer in the catalog. The search collection is reachable
only from its VPC (ADR-32): this job writes the finished index documents to the
images bucket (catalog-index/) and invokes VoiceShop-CatalogIndexWriter, which
rebuilds the index from them inside the VPC.

Environment: IMAGES_BUCKET, PRODUCTS_TABLE, INDEX_WRITER_FUNCTION, AWS_REGION
"""

import concurrent.futures
import datetime
import hashlib
import json
import os
import random
import sys
import time
import zipfile
from pathlib import Path

import boto3
from botocore.config import Config
from botocore.exceptions import ClientError

from catalog_lib.records import catalog_meta_item, dynamodb_item, embedding_text, image_key, opensearch_document, problems

HERE = Path(__file__).resolve().parent
LOCK = HERE / 'catalog' / 'catalog.lock.json'
EMBEDDING_MODEL_ID = 'amazon.titan-embed-text-v2:0'
EMBEDDING_DIMENSIONS = 1024
CONCURRENCY = 16
EMBED_MAX_ATTEMPTS = 8
INDEX_DOCUMENTS_KEY = 'catalog-index/documents.ndjson'
# The index writer rebuilds the index and waits until it is searchable (up to ~3 min).
INDEX_WRITER_TIMEOUT_SECONDS = 900

REGION = os.environ.get('AWS_REGION', 'us-east-1')
session = boto3.Session(region_name=REGION)
s3 = session.client('s3', config=Config(retries={'total_max_attempts': 3, 'mode': 'standard'},
                                        max_pool_connections=CONCURRENCY * 2))
# Embedding throttling is retried by embed() with its own backoff, not the SDK.
bedrock = session.client('bedrock-runtime', config=Config(retries={'total_max_attempts': 1},
                                                          max_pool_connections=CONCURRENCY * 2))
dynamodb = session.resource('dynamodb')
lambda_client = session.client('lambda', config=Config(read_timeout=INDEX_WRITER_TIMEOUT_SECONDS,
                                                        retries={'total_max_attempts': 1}))


# ---------------------------------------------------------------------------
# Search index, through VoiceShop-CatalogIndexWriter (inside the VPC)
# ---------------------------------------------------------------------------
def rebuild_index(bucket, documents):
    """Writes the documents as NDJSON, has the index writer rebuild the index from
    them, then removes the file. Returns (indexed, searchable)."""
    s3.put_object(Bucket=bucket, Key=INDEX_DOCUMENTS_KEY, ContentType='application/x-ndjson',
                  Body='\n'.join(json.dumps(d) for d in documents).encode())
    try:
        response = lambda_client.invoke(FunctionName=os.environ['INDEX_WRITER_FUNCTION'],
                                        Payload=json.dumps({'key': INDEX_DOCUMENTS_KEY}).encode())
        result = json.loads(response['Payload'].read() or b'{}')
        if response.get('FunctionError'):
            raise RuntimeError(f'index writer failed: {result.get("errorMessage", result)}')
        return result['indexed'], result['searchable']
    finally:
        s3.delete_object(Bucket=bucket, Key=INDEX_DOCUMENTS_KEY)


# ---------------------------------------------------------------------------
# Steps
# ---------------------------------------------------------------------------
def open_catalog():
    """The catalog zip named by the lock file, after checking its sha256."""
    lock = json.loads(LOCK.read_text())
    path = LOCK.parent / lock['file']
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    if digest != lock['sha256']:
        sys.exit(f'❌ {path.name} sha256 {digest} does not match catalog.lock.json ({lock["sha256"]})')
    archive = zipfile.ZipFile(path)
    manifest = json.loads(archive.read('manifest.json'))
    products = [json.loads(line) for line in archive.read('catalog.jsonl').decode().splitlines() if line.strip()]
    return lock, manifest, archive, products


def upload_image(archive, product, bucket):
    try:
        s3.put_object(Bucket=bucket, Key=image_key(product['asin']), Body=archive.read(product['image']),
                      ContentType='image/webp', CacheControl='max-age=86400')
        return True
    except Exception as err:  # noqa: BLE001 -- skip the item and count it
        print(f'⚠️ image upload failed for {product["asin"]}: {err}')
        return False


def embed(product):
    body = json.dumps({'inputText': embedding_text(product), 'dimensions': EMBEDDING_DIMENSIONS, 'normalize': True})
    for attempt in range(EMBED_MAX_ATTEMPTS):
        try:
            response = bedrock.invoke_model(modelId=EMBEDDING_MODEL_ID, body=body,
                                            contentType='application/json', accept='application/json')
            return json.loads(response['body'].read())['embedding']
        except ClientError as err:
            code = err.response['Error']['Code']
            if code not in ('ThrottlingException', 'ServiceUnavailableException', 'ModelNotReadyException') \
                    or attempt == EMBED_MAX_ATTEMPTS - 1:
                print(f'⚠️ embedding failed for {product["asin"]}: {code}')
                return None
            time.sleep(min(30, 2 ** attempt) * (0.5 + random.random() / 2))  # noqa: S311 (jitter)
    return None


def delete_stale_products(table, keep_asins):
    """Deletes PRODUCT# items from earlier runs that are no longer in the catalog."""
    stale = []
    scan = {'ProjectionExpression': 'PK, SK', 'FilterExpression': 'begins_with(PK, :p)',
            'ExpressionAttributeValues': {':p': 'PRODUCT#'}}
    while True:
        page = table.scan(**scan)
        stale.extend(i for i in page['Items'] if i['PK'][len('PRODUCT#'):] not in keep_asins)
        if 'LastEvaluatedKey' not in page:
            break
        scan['ExclusiveStartKey'] = page['LastEvaluatedKey']
    with table.batch_writer() as batch:
        for item in stale:
            batch.delete_item(Key={'PK': item['PK'], 'SK': item['SK']})
    return len(stale)


def delete_stale_images(bucket, keep_asins):
    """Deletes images under products/ that belong to no current product (or are an old format)."""
    keep = {image_key(a) for a in keep_asins}
    stale = []
    for page in s3.get_paginator('list_objects_v2').paginate(Bucket=bucket, Prefix='products/'):
        stale.extend(o['Key'] for o in page.get('Contents', []) if o['Key'] not in keep)
    for start in range(0, len(stale), 1000):
        s3.delete_objects(Bucket=bucket, Delete={'Objects': [{'Key': k} for k in stale[start:start + 1000]], 'Quiet': True})
    return len(stale)


def main():
    images_bucket = os.environ['IMAGES_BUCKET']
    table = dynamodb.Table(os.environ['PRODUCTS_TABLE'])

    lock, manifest, archive, rows = open_catalog()
    print(f'📥 Loading {lock["file"]} ({manifest.get("products")} products, {manifest.get("categories")} categories)')
    invalid = {}
    products = []
    for row in rows:
        found = problems(row)
        if found:
            invalid[row.get('asin', '?')] = found
        else:
            products.append(row)
    if invalid:
        print(f'⚠️ {len(invalid)} rows skipped, e.g. {next(iter(invalid.items()))}')

    with concurrent.futures.ThreadPoolExecutor(CONCURRENCY) as pool:
        uploaded = list(pool.map(lambda p: upload_image(archive, p, images_bucket), products))
    with_images = [p for p, ok in zip(products, uploaded) if ok]
    print(f'🖼️ {len(with_images)} images uploaded, {len(products) - len(with_images)} failed')

    with concurrent.futures.ThreadPoolExecutor(CONCURRENCY) as pool:
        embeddings = list(pool.map(embed, with_images))
    final = [(p, e) for p, e in zip(with_images, embeddings) if e is not None]
    print(f'🧮 {len(final)} embeddings, {len(with_images) - len(final)} failed')
    loaded = [p for p, _ in final]

    indexed, searchable = rebuild_index(images_bucket, [opensearch_document(p, e) for p, e in final])
    with table.batch_writer() as batch:
        for product in loaded:
            batch.put_item(Item=dynamodb_item(product))
    keep = {p['asin'] for p in loaded}
    deleted_products = delete_stale_products(table, keep)
    deleted_images = delete_stale_images(images_bucket, keep)

    counts = {
        'rows': len(rows), 'invalid': len(invalid), 'imageFailures': len(products) - len(with_images),
        'embeddingFailures': len(with_images) - len(final), 'writtenDynamoDB': len(loaded),
        'writtenOpenSearch': indexed, 'deletedStaleProducts': deleted_products, 'deletedStaleImages': deleted_images,
    }
    table.put_item(Item=catalog_meta_item(
        loaded, counts,
        source={'file': lock['file'], 'sha256': lock['sha256'], 'kind': 'synthetic',
                'note': manifest.get('note', '')},
        curated_at=datetime.datetime.now(datetime.timezone.utc).isoformat(timespec='seconds'),
        taxonomy=manifest.get('taxonomy'),
    ))
    print(json.dumps(counts, indent=2))
    print(f'🔎 {searchable}/{indexed} documents searchable')
    if searchable < indexed:
        print('⚠️ Not all documents were searchable before the wait ended; they should appear shortly.')
    return 0 if loaded else 1


if __name__ == '__main__':
    sys.exit(main())
